/// <reference types="node" />
/**
 * Regenerates vectors/spark-accounts.json: identity public keys the enclave must produce for
 * account groups 0 and 1 on mainnet and regtest under the public test mnemonic. Values come from a
 * real local signer — `createSparkSigner(sparkAccountKey(seed, network, account))` on the shipped
 * spark.wasm — so the vector pins the exact derivation chain the kernel runs.
 *
 * Run from packages/wallet-worker: bun scripts/spark-accounts-vector.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { pbkdf2 } from "@noble/hashes/pbkdf2.js";
import { sha512 } from "@noble/hashes/sha2.js";
import { utf8ToBytes } from "@noble/hashes/utils.js";

import { loadSparkWasm } from "@qntx/spark-wasm/browser";
import { createSparkSigner, sparkAccountKey } from "@qntx/spark/signer";
import type { SparkNetwork } from "@qntx/spark/signer";

// The public BIP-39 test mnemonic. Test only — never fund.
const MNEMONIC =
  "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about";

const seed = pbkdf2(sha512, utf8ToBytes(MNEMONIC.normalize("NFKD")), utf8ToBytes("mnemonic"), {
  c: 2048,
  dkLen: 64,
});

const wasm = readFileSync(
  join(import.meta.dirname, "..", "node_modules", "@qntx", "spark-wasm", "dist", "spark.wasm"),
);
const crypto = await loadSparkWasm({ module: wasm });

const random = (length: number): Uint8Array =>
  globalThis.crypto.getRandomValues(new Uint8Array(length));

const vectors: Array<{
  groupIndex: number;
  network: SparkNetwork;
  account: number;
  identityPublicKey: string;
}> = [];
for (const network of ["mainnet", "regtest"] as const) {
  for (const groupIndex of [0, 1] as const) {
    const account = network === "mainnet" ? groupIndex + 1 : groupIndex;
    const accountKey = sparkAccountKey(seed, network, account);
    const signer = createSparkSigner({ crypto, accountKey, network, random });
    // oxlint-disable-next-line eslint/no-await-in-loop -- one signer at a time: it is disposed before the next is created
    const identity = await signer.identityPublicKey();
    signer.dispose();
    accountKey.fill(0);
    vectors.push({
      groupIndex,
      network,
      account,
      identityPublicKey: Buffer.from(identity).toString("hex"),
    });
  }
}

const out = {
  comment:
    "Spark identity public keys (33-byte compressed hex) per account group and network under the public BIP-39 test mnemonic — test only, never fund. Generated by packages/wallet-worker/scripts/spark-accounts-vector.ts with createSparkSigner(sparkAccountKey(seed, network, account)) on the shipped spark.wasm; account = groupIndex + 1 on mainnet, groupIndex on regtest.",
  mnemonic: MNEMONIC,
  vectors,
};

const target = join(import.meta.dirname, "..", "..", "..", "vectors", "spark-accounts.json");
writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${target}`);
