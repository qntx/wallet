#!/usr/bin/env node
/**
 * Compile the shipped kernel bundle to Hermes bytecode with the consuming app's own hermesc,
 * resolved through its installed react-native → hermes-compiler. Hermes only loads its own bytecode
 * version, so the bytecode is compiled at the app's native build time, never shipped.
 *
 * Usage: node compile-kernel.mjs <outDir> Emits <outDir>/kernel.hpp (KERNEL_BYTECODE /
 * KERNEL_BYTECODE_SIZE), rewritten only when the content changes so incremental builds do not
 * recompile C++.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const { 2: outDirArg } = process.argv;
if (outDirArg === undefined || outDirArg === "") {
  console.error("usage: node compile-kernel.mjs <outDir>");
  process.exit(2);
}
const outDir = resolve(outDirArg);
const packageDir = fileURLToPath(new URL("..", import.meta.url));
const generated = resolve(packageDir, "kernel", "generated");
const entry = resolve(generated, "kernel-entry.js");
const manifestPath = resolve(generated, "kernel.manifest.json");

// The manifest's bundle SHA is the contract: a tampered or stale bundle must
// fail the native build instead of shipping a kernel nobody recorded.
/**
 * @param {unknown} value
 * @returns {value is { bundles?: { file: string; sha256: string }[] }}
 */
function isManifest(value) {
  return typeof value === "object" && value !== null && "bundles" in value;
}
const parsed = /** @type {unknown} */ (JSON.parse(readFileSync(manifestPath, "utf8")));
if (!isManifest(parsed)) {
  console.error("kernel.manifest.json: expected an object with a bundles field");
  process.exit(1);
}
const declared = parsed.bundles?.find((b) => b.file === "kernel-entry.js")?.sha256;
const actual = createHash("sha256").update(readFileSync(entry)).digest("hex");
if (typeof declared !== "string" || declared !== actual) {
  console.error(
    `kernel-entry.js sha256 mismatch: kernel.manifest.json declares ` +
      `${declared ?? "<missing>"}, the bundle hashes ${actual} — ` +
      `run bun run native:kernel and commit both artifacts`,
  );
  process.exit(1);
}

// Resolve through the app's own react-native so the hermesc version matches the
// Hermes runtime the app links — the entire reason bytecode is compiled here.
const requireFromPackage = createRequire(resolve(packageDir, "package.json"));
const rnPkg = requireFromPackage.resolve("react-native/package.json");
const requireFromRn = createRequire(rnPkg);
const hermesPkg = requireFromRn.resolve("hermes-compiler/package.json");
const platformDir =
  process.platform === "darwin"
    ? "osx-bin"
    : process.platform === "linux"
      ? "linux64-bin"
      : "win64-bin";
const hermesc = resolve(
  dirname(hermesPkg),
  "hermesc",
  platformDir,
  process.platform === "win32" ? "hermesc.exe" : "hermesc",
);

mkdirSync(outDir, { recursive: true });
const tmpHbc = resolve(outDir, ".kernel.hbc");
try {
  execFileSync(hermesc, ["-O", "-emit-async-break-check", "-emit-binary", "-out", tmpHbc, entry], {
    stdio: ["ignore", "pipe", "inherit"],
  });
} catch (error) {
  console.error(
    `hermesc failed on ${entry}: ${error instanceof Error ? error.message : String(error)}`,
  );
  process.exit(1);
}
const bytes = readFileSync(tmpHbc);
rmSync(tmpHbc);

const body = [
  "// Generated by scripts/compile-kernel.mjs — do not edit.",
  "#pragma once",
  "",
  "#include <cstdint>",
  "#include <cstddef>",
  "",
  "namespace qntx {",
  "inline constexpr uint8_t KERNEL_BYTECODE[] = {",
];
for (let i = 0; i < bytes.length; i += 16) {
  const chunk = [...bytes.subarray(i, i + 16)]
    .map((b) => `0x${b.toString(16).padStart(2, "0")}`)
    .join(",");
  body.push(`  ${chunk}${i + 16 < bytes.length ? "," : ""}`);
}
body.push("};", `inline constexpr size_t KERNEL_BYTECODE_SIZE = ${bytes.length};`, "}");

const header = `${body.join("\n")}\n`;
const headerPath = resolve(outDir, "kernel.hpp");
if (!existsSync(headerPath) || readFileSync(headerPath, "utf8") !== header) {
  writeFileSync(headerPath, header);
}
console.log(`kernel.hpp: ${bytes.length} bytes compiled`);
