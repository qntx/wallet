/// <reference types="node" />
/**
 * Regenerates vectors/sync-key.json without importing kernel code: the wallet metadata sync key is
 * the NIP-06 secret at the reserved index segment — m/44'/1237'/2147483647'/0/0 — derived from the
 * test mnemonic by @scure/bip32 + the x-only schnorr public key by @noble/curves. The kernel's
 * nostr.syncKey must answer this publicKey for this mnemonic.
 *
 * Run from the repo root: bun scripts/vectors/sync-key.ts
 */
import { writeFileSync } from "node:fs";

import { schnorr } from "@noble/curves/secp256k1.js";
import { bytesToHex } from "@noble/hashes/utils.js";
import { HDKey } from "@scure/bip32";
import { mnemonicToSeedSync } from "@scure/bip39";

const MNEMONIC = "leader monkey parrot ring guide accident before fence cannon height naive bean";
const PATH = "m/44'/1237'/2147483647'/0/0";

const master = HDKey.fromMasterSeed(mnemonicToSeedSync(MNEMONIC.normalize("NFKD"), ""));
const node = master.derive(PATH);
const { privateKey } = node;
if (privateKey === null || privateKey === undefined) {
  throw new Error("derivation produced no key");
}
const publicKey = bytesToHex(schnorr.getPublicKey(privateKey));

const out = {
  comment:
    "Wallet metadata sync-key vector generated by scripts/vectors/sync-key.ts (independent of the kernel): the test mnemonic's NIP-06 secret at the reserved segment m/44'/1237'/2147483647'/0/0, above every identity index.",
  vector: {
    mnemonic: MNEMONIC,
    path: PATH,
    privateKey: bytesToHex(privateKey),
    publicKey,
  },
};

writeFileSync("vectors/sync-key.json", `${JSON.stringify(out, null, 2)}\n`);
console.log("wrote vectors/sync-key.json", publicKey);
node.wipePrivateData();
master.wipePrivateData();
