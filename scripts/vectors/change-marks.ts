/// <reference types="node" />
/**
 * Regenerates vectors/vault/change-marks.json without importing kernel code: the canonical
 * `change-marks` record header — `{"walletId":"…","marks":[{groupIndex,purpose,network,index}]}` in
 * fixed key order, entries sorted by (groupIndex, purpose, network) — plus rejection cases, one per
 * invariant the header parser enforces.
 *
 * The walletId is computed independently: node:crypto sha256("qntx-wallet/wallet-id/v1" ‖ master)
 * [0..8] over the @scure/bip32 master of the same fixed seed the other vault vectors use.
 *
 * Run from the repo root: bun scripts/vectors/change-marks.ts
 */
// oxlint-disable typescript/no-unsafe-type-assertion -- rejects mutate a parsed copy of the
// canonical document whose shape the cases below name by construction.
// oxlint-disable typescript/no-non-null-assertion -- same reason: indexes into that known shape.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

import { bytesToHex, hexToBytes } from "@noble/hashes/utils.js";
import { HDKey } from "@scure/bip32";

const sha256 = (data: Uint8Array): Uint8Array => createHash("sha256").update(data).digest();
const walletId = (master: Uint8Array): string =>
  bytesToHex(
    sha256(
      new Uint8Array([...new TextEncoder().encode("qntx-wallet/wallet-id/v1"), ...master]),
    ).subarray(0, 8),
  );

const SEED = "000102030405060708090a0b0c0d0e0f";
const NETWORK = "bip122:000000000019d6689c085ae165831e93";
const TESTNET = "bip122:000000000933ea01ad0ee984209779ba";

const master = HDKey.fromMasterSeed(hexToBytes(SEED));
if (master.publicKey === null) {
  throw new Error("no master public key");
}
const WALLET_ID = walletId(master.publicKey);

/* Two marks for the fixed wallet: group 0 bip84 mainnet at index 20, group 1 bip86 testnet at
 * index 3 — one key per tuple field, spelled in the encoder's order. */
const headerInput = {
  walletId: WALLET_ID,
  marks: [
    { groupIndex: 0, purpose: 84, network: NETWORK, index: 20 },
    { groupIndex: 1, purpose: 86, network: TESTNET, index: 3 },
  ],
};
const headerText = JSON.stringify(headerInput);

const mutate = (patch: (value: Record<string, unknown>) => void): string => {
  const value = JSON.parse(headerText) as Record<string, unknown>;
  patch(value);
  return JSON.stringify(value);
};
const mutateMark = (at: number, patch: (mark: Record<string, unknown>) => void): string =>
  mutate((value) => {
    patch((value["marks"] as Array<Record<string, unknown>>)[at]!);
  });

const rejects: Array<{ name: string; text: string }> = [
  {
    name: "extra-key",
    text: mutate((v) => {
      v["extra"] = true;
    }),
  },
  {
    name: "missing-marks",
    text: mutate((v) => {
      delete v["marks"];
    }),
  },
  {
    name: "marks-not-array",
    text: mutate((v) => {
      v["marks"] = {};
    }),
  },
  {
    name: "bad-wallet-id",
    text: mutate((v) => {
      v["walletId"] = WALLET_ID.toUpperCase();
    }),
  },
  {
    name: "mark-extra-key",
    text: mutateMark(0, (m) => {
      m["extra"] = 0;
    }),
  },
  {
    name: "mark-missing-key",
    text: mutateMark(0, (m) => {
      delete m["index"];
    }),
  },
  {
    name: "purpose-not-segwit-family",
    text: mutateMark(0, (m) => {
      m["purpose"] = 145;
    }),
  },
  {
    name: "network-not-caip2",
    text: mutateMark(0, (m) => {
      m["network"] = "bitcoin-mainnet";
    }),
  },
  {
    name: "index-negative",
    text: mutateMark(0, (m) => {
      m["index"] = -1;
    }),
  },
  {
    name: "index-non-integer",
    text: mutateMark(0, (m) => {
      m["index"] = 20.5;
    }),
  },
  {
    name: "index-past-2^31",
    text: mutateMark(0, (m) => {
      m["index"] = 2_147_483_648;
    }),
  },
  {
    name: "unsorted",
    text: mutate((v) => {
      (v["marks"] as unknown[]).reverse();
    }),
  },
  {
    name: "duplicate",
    text: mutate((v) => {
      const marks = v["marks"] as unknown[];
      marks.push(marks[0]);
    }),
  },
];

writeFileSync(
  "vectors/vault/change-marks.json",
  `${JSON.stringify(
    {
      comment:
        'Canonical change-marks record header generated by scripts/vectors/change-marks.ts — independent of the kernel. `{"walletId":"…","marks":[{groupIndex,purpose,network,index}]}` in fixed key order, marks sorted by (groupIndex, purpose, network); rejects each break one parser invariant.',
      walletId: WALLET_ID,
      header: { input: headerInput, text: headerText },
      rejects,
    },
    null,
    2,
  )}\n`,
);
console.log("wrote vectors/vault/change-marks.json");
