/// <reference types="node" />
/**
 * Regenerates vectors/key-id.json without importing kernel code:
 *
 * KeyId = hex(SHA-256(UTF-8("qntx-wallet/key-id/v1") ‖ familyByte ‖ publicKey)[0..8))
 *
 * FamilyByte: 0x01 evm, 0x02 solana, 0x03 bitcoin — publicKey is the family's canonical public key
 * bytes (33-byte compressed secp256k1 for evm, 32-byte ed25519 for solana/bitcoin).
 *
 * Run from the repo root: bun scripts/vectors/key-id.ts
 */
import { writeFileSync } from "node:fs";

import { sha256 } from "@noble/hashes/sha2.js";
import { bytesToHex, concatBytes, hexToBytes, utf8ToBytes } from "@noble/hashes/utils.js";

const FAMILY_BYTE: Record<string, number> = { evm: 0x01, solana: 0x02, bitcoin: 0x03 };

function keyIdOf(family: string, publicKey: Uint8Array): string {
  return bytesToHex(
    sha256(
      concatBytes(
        utf8ToBytes("qntx-wallet/key-id/v1"),
        Uint8Array.of(FAMILY_BYTE[family] ?? 0),
        publicKey,
      ),
    ).slice(0, 8),
  );
}

const cases = [
  {
    name: "evm-hardhat0",
    family: "evm",
    publicKey: "038318535b54105d4a7aae60c08fc45f9687181b4fdfc625bd1a753fa7397fed75",
  },
  {
    name: "evm-second",
    family: "evm",
    publicKey: "02ba5734d8f7091719471e7f7ed6b9df170dc70cc661ca05e688601ad984f068b0",
  },
  {
    name: "solana-slip10-master",
    family: "solana",
    publicKey: "a4b2856bfec510abab89753fac1ac0e1112364e7d250545963f135f2a33188ed",
  },
  {
    name: "bitcoin-same-pub",
    family: "bitcoin",
    publicKey: "a4b2856bfec510abab89753fac1ac0e1112364e7d250545963f135f2a33188ed",
  },
] as const;

const vectors = cases.map((c) => ({
  name: c.name,
  family: c.family,
  publicKey: c.publicKey,
  familyByte: FAMILY_BYTE[c.family],
  keyId: keyIdOf(c.family, hexToBytes(c.publicKey)),
}));

writeFileSync(
  "vectors/key-id.json",
  `${JSON.stringify(
    {
      comment:
        'keyId = hex(SHA-256(UTF-8("qntx-wallet/key-id/v1") ‖ familyByte ‖ publicKey)[0..8)) — ' +
        "generated by scripts/vectors/key-id.ts, independent of the kernel. familyByte: " +
        "0x01 evm, 0x02 solana, 0x03 bitcoin. Same public key on two families maps to different keyIds.",
      familyByte: FAMILY_BYTE,
      vectors,
    },
    null,
    2,
  )}\n`,
);
console.log(`vectors/key-id.json: ${vectors.map((v) => `${v.name}=${v.keyId}`).join(", ")}`);
