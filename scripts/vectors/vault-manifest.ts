/// <reference types="node" />
/**
 * Regenerates vectors/vault-manifest.json without importing kernel code: a fixed vault image, the
 * structure digest its manifest commits to, and that manifest record sealed under a fixed DEK and
 * nonce. The digest is spelled out from its definition:
 *
 * SHA-256(lp("qntx-wallet/vault/v1/manifest") ‖ u32be(format) ‖ lp(keyId) ‖ u32be(#records) ‖ per
 * record: lp(kind) ‖ lp(id) ‖ lp(header) ‖ lp(sealed) ‖ u32be(#factors) ‖ per factor: lp(kind) ‖
 * lp(id) ‖ lp(header) ‖ lp(sealed)), lp(x) = u32be(byteLength(x)) ‖ x, strings UTF-8, the manifest
 * record left out, records ordered by (kind, id), factors by id.
 *
 * The manifest record is `manifest/default` with header `{}`, sealed with envelope v1 under the
 * record context `qntx-wallet/vault/v1/record/manifest/default`.
 *
 * Run from the repo root: bun scripts/vectors/vault-manifest.ts
 */
import { writeFileSync } from "node:fs";

import { xchacha20poly1305 } from "@noble/ciphers/chacha.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { bytesToHex, concatBytes, hexToBytes, utf8ToBytes } from "@noble/hashes/utils.js";

type Row = { kind: string; id: string; header: string; sealed: string };

const fill = (byte: number, length: number): string =>
  bytesToHex(new Uint8Array(length).fill(byte));

const META = {
  format: 5,
  revision: 7,
  keyId: "00112233445566778899aabbccddeeff",
  failedAttempts: 2,
  lastFailureAt: 1767225600000,
};

// Stored in an order the digest does not use: the digest sorts.
const RECORDS: Row[] = [
  { kind: "policy", id: "blind-signing", header: '{"createdAt":1}', sealed: fill(0x31, 41) },
  { kind: "entropy", id: "ffeeddccbbaa9988", header: '{"w":2}', sealed: fill(0x32, 57) },
  { kind: "entropy", id: "0011223344556677", header: '{"w":1}', sealed: fill(0x33, 57) },
  { kind: "backup-key", id: "default", header: '{"id":"x"}', sealed: fill(0x34, 73) },
];
const FACTORS: Row[] = [
  { kind: "passkey", id: "ff".repeat(16), header: '{"p":2}', sealed: fill(0x41, 121) },
  { kind: "password", id: "01".repeat(16), header: '{"p":1}', sealed: fill(0x42, 121) },
];

const DEK = fill(0x5d, 32);
const NONCE = fill(0x6e, 24);

function u32(value: number): Uint8Array {
  const out = new Uint8Array(4);
  new DataView(out.buffer).setUint32(0, value);
  return out;
}

function lp(value: string | Uint8Array): Uint8Array {
  const bytes = typeof value === "string" ? utf8ToBytes(value) : value;
  return concatBytes(u32(bytes.length), bytes);
}

const order = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

function rowBytes(row: Row): Uint8Array {
  return concatBytes(lp(row.kind), lp(row.id), lp(row.header), lp(hexToBytes(row.sealed)));
}

function imageDigest(records: Row[], factors: Row[]): Uint8Array {
  const sortedRecords = [...records].toSorted((a, b) => order(a.kind, b.kind) || order(a.id, b.id));
  const sortedFactors = [...factors].toSorted((a, b) => order(a.id, b.id));
  return sha256(
    concatBytes(
      lp("qntx-wallet/vault/v1/manifest"),
      u32(META.format),
      lp(META.keyId),
      u32(sortedRecords.length),
      ...sortedRecords.map(rowBytes),
      u32(sortedFactors.length),
      ...sortedFactors.map(rowBytes),
    ),
  );
}

function sealedManifest(digest: Uint8Array): string {
  const context = utf8ToBytes("qntx-wallet/vault/v1/record/manifest/default");
  const header = utf8ToBytes("{}");
  const aad = concatBytes(new Uint8Array([0x01]), u32(context.length).slice(2), context, header);
  const nonce = hexToBytes(NONCE);
  const sealed = concatBytes(
    new Uint8Array([0x01]),
    nonce,
    xchacha20poly1305(hexToBytes(DEK), nonce, aad).encrypt(digest),
  );
  return bytesToHex(sealed);
}

const digest = imageDigest(RECORDS, FACTORS);

// A second image carrying an hl-agent row: the manifest authenticates module-owned record kinds
// too, so a store writer cannot add, drop or rewrite one undetected.
const AGENT_RECORDS: Row[] = [
  ...RECORDS,
  {
    kind: "hl-agent",
    id: `0x${"ab".repeat(20)}`,
    header:
      '{"walletId":"0011223344556677","groupIndex":0,"owner":"0x9858EfFD232B4033E47d90003D41EC34EcaEda94","network":"Mainnet","name":"bot-1","validUntil":1782777600000,"createdAt":1767225600000}',
    sealed: fill(0x35, 57),
  },
];
const agentDigest = imageDigest(AGENT_RECORDS, FACTORS);

const out = {
  comment:
    "TEST ONLY. Vault manifest (format 5): a fixed image, the structure digest its manifest commits to, and the manifest record sealed under a fixed DEK/nonce. `withAgent` is the same image plus an hl-agent row. Generated by scripts/vectors/vault-manifest.ts (noble only, independent of the kernel).",
  image: { meta: META, records: RECORDS, factors: FACTORS },
  digest: bytesToHex(digest),
  dek: DEK,
  nonce: NONCE,
  manifest: { kind: "manifest", id: "default", header: "{}", sealed: sealedManifest(digest) },
  withAgent: {
    image: { meta: META, records: AGENT_RECORDS, factors: FACTORS },
    digest: bytesToHex(agentDigest),
    manifest: {
      kind: "manifest",
      id: "default",
      header: "{}",
      sealed: sealedManifest(agentDigest),
    },
  },
};

writeFileSync("vectors/vault-manifest.json", `${JSON.stringify(out, null, 2)}\n`);
console.log("wrote vectors/vault-manifest.json");
