/// <reference types="node" />
/**
 * Regenerates vectors/vault-anchor.json without importing kernel code: the 21-byte vault-anchor
 * record spelled out byte by byte —
 *
 * U8 version = 1 ‖ u64be revision ‖ u32be failedAttempts ‖ u64be lastFailureAt
 *
 * `accept` cases give hex plus the decoded field set the kernel must read back (encode must
 * reproduce the hex byte for byte); `reject` cases must throw — wrong length, an unknown version or
 * a u64 field above Number.MAX_SAFE_INTEGER (high word > 0x001fffff, so a decode cannot give an
 * exact integer back).
 *
 * Run from the repo root: bun scripts/vectors/vault-anchor.ts
 */
import { writeFileSync } from "node:fs";

import { bytesToHex, hexToBytes } from "@noble/hashes/utils.js";

type State = { revision: number; failedAttempts: number; lastFailureAt: number };

const BYTES = 21;
const VERSION = 1;
const MAX_SAFE = 0x1f_ff_ff_ff_ff_ff_ff; // Number.MAX_SAFE_INTEGER

function encode(state: State): string {
  const out = new Uint8Array(BYTES);
  const view = new DataView(out.buffer);
  view.setUint8(0, VERSION);
  view.setUint32(1, Math.floor(state.revision / 0x1_00_00_00_00));
  view.setUint32(5, state.revision % 0x1_00_00_00_00);
  view.setUint32(9, state.failedAttempts);
  view.setUint32(13, Math.floor(state.lastFailureAt / 0x1_00_00_00_00));
  view.setUint32(17, state.lastFailureAt % 0x1_00_00_00_00);
  return bytesToHex(out);
}

/** Hex → the raw 21 bytes, patched at byte offset (offset = 1-based field start). */
function patch(base: State, patches: Array<{ offset: number; bytes: number[] }>): string {
  const out = hexToBytes(encode(base));
  for (const { offset, bytes } of patches) {
    out.set(bytes, offset);
  }
  return bytesToHex(out);
}

const TYPICAL: State = { revision: 7, failedAttempts: 2, lastFailureAt: 1_767_225_600_000 };
const MAXED: State = { revision: MAX_SAFE, failedAttempts: 0xff_ff_ff_ff, lastFailureAt: MAX_SAFE };

const accept = [
  {
    name: "zero",
    state: { revision: 0, failedAttempts: 0, lastFailureAt: 0 },
    hex: encode({ revision: 0, failedAttempts: 0, lastFailureAt: 0 }),
  },
  { name: "typical", state: TYPICAL, hex: encode(TYPICAL) },
  { name: "max-safe", state: MAXED, hex: encode(MAXED) },
];

const typicalHex = encode(TYPICAL);
const reject = [
  { name: "short", hex: typicalHex.slice(0, 40) },
  { name: "long", hex: `${typicalHex}00` },
  { name: "version-0", hex: patch(TYPICAL, [{ offset: 0, bytes: [0] }]) },
  { name: "version-2", hex: patch(TYPICAL, [{ offset: 0, bytes: [2] }]) },
  {
    name: "revision-unsafe",
    // u64be high word 0x00200000 → value 2^53, one past MAX_SAFE_INTEGER.
    hex: patch(TYPICAL, [{ offset: 1, bytes: [0, 0x20, 0, 0, 0, 0, 0, 0] }]),
  },
  {
    name: "lastFailureAt-unsafe",
    hex: patch(TYPICAL, [{ offset: 13, bytes: [0, 0x20, 0, 0, 0, 0, 0, 0] }]),
  },
];

const out = {
  comment:
    "TEST ONLY. Vault anchor records: u8 version = 1 ‖ u64be revision ‖ u32be failedAttempts ‖ u64be lastFailureAt. `accept` decodes to `state` and encodes back to `hex`; `reject` must throw (length, version or a u64 above Number.MAX_SAFE_INTEGER). Generated by scripts/vectors/vault-anchor.ts — DataView only, no kernel imports.",
  format: { bytes: BYTES, version: VERSION },
  accept,
  reject,
};

writeFileSync("vectors/vault-anchor.json", `${JSON.stringify(out, null, 2)}\n`);
console.log("wrote vectors/vault-anchor.json");
