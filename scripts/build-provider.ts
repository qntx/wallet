/**
 * Build the in-app-browser provider script: bundle `src/connect/inject/provider.ts` into one
 * classic-script string with the repo's pinned bundler (rolldown via vite-plus, same as the kernel
 * bundle — deterministic across machines), then emit `src/connect/inject.generated.ts` exporting
 * the script. `--check` rebuilds to a temp and byte-compares, so `lint` fails on a stale artifact
 * (the kernel-bundle freshness check does the same against `git diff`).
 */
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "vite";

const check = process.argv.includes("--check");

const entry = fileURLToPath(
  new URL("../packages/wallet-engine/src/connect/inject/provider.ts", import.meta.url),
);
const outDir = mkdtempSync(join(tmpdir(), "qntx-provider-build-"));
const generated = fileURLToPath(
  new URL("../packages/wallet-engine/src/connect/inject.generated.ts", import.meta.url),
);

await build({
  configFile: false,
  logLevel: "warn",
  build: {
    lib: { entry, formats: ["iife"], name: "qntxProvider", fileName: () => "provider.js" },
    outDir,
    target: "es2022",
    minify: false,
    emptyOutDir: true,
    write: true,
  },
});

const script = `${readFileSync(`${outDir}/provider.js`, "utf8").trim()}\n`;
if (/^\s*(import|export)\s/m.test(script) || !/^var qntxProvider = /m.test(script)) {
  throw new Error(
    "provider.js is not a self-contained qntxProvider IIFE — check the bundler output",
  );
}

const source =
  `// GENERATED by scripts/build-provider.ts — do not edit; run \`bun run connect:provider\`.\n` +
  `export const PROVIDER_SCRIPT: string = ${JSON.stringify(script)};\n`;

if (check) {
  const committed = readFileSync(generated, "utf8");
  if (committed !== source) {
    throw new Error("inject.generated.ts is stale — run `bun run connect:provider`");
  }
  console.log(`inject.generated.ts: fresh (${script.length} bytes)`);
} else {
  writeFileSync(generated, source);
  console.log(`inject.generated.ts: ${script.length} bytes written`);
}
