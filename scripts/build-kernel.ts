import { execFileSync } from "node:child_process";
/**
 * Build the kernel runtime payload: bundle `kernel/kernel-entry.ts` into one classic script with
 * the repo's pinned bundler (rolldown via vite-plus — deterministic across machines, unlike `bun
 * build` whose output varies by bun version), compile it to bytecode with the harness's hermesc
 * (the runtime the app actually ships), and emit `cpp/generated/kernel.hpp` — the bytes plus their
 * SHA-256, verified by `KernelHost::start`.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "vite";

const root = fileURLToPath(new URL("..", import.meta.url));
const harness = resolve(root, "apps/harness");
const entry = resolve(root, "packages/wallet-native/kernel/kernel-entry.ts");
const outDir = resolve(root, "packages/wallet-native/cpp/generated");
const tmpJs = resolve(outDir, ".kernel-entry.js");
const tmpHbc = resolve(outDir, ".kernel.hbc");

const hermesc = (() => {
  const require = createRequire(resolve(harness, "package.json"));
  const pkg = require.resolve("hermes-compiler/package.json");
  const platformDir =
    process.platform === "darwin"
      ? "osx-bin"
      : process.platform === "linux"
        ? "linux64-bin"
        : "win64-bin";
  return resolve(
    dirname(pkg),
    "hermesc",
    platformDir,
    process.platform === "win32" ? "hermesc.exe" : "hermesc",
  );
})();

mkdirSync(outDir, { recursive: true });

// One iife classic-script bundle — hermesc needs a classic script, not an ES module.
await build({
  configFile: false,
  logLevel: "warn",
  build: {
    lib: { entry, formats: ["iife"], name: "qntxKernelEntry", fileName: () => "kernel-entry.js" },
    outDir,
    emptyOutDir: false,
    minify: false,
    target: "es2017",
  },
});
// The bundle stays committed under cpp/generated — unlike the hermesc output it reproduces
// byte-for-byte on any machine (sha256 below), so it is the artifact CI diffs. hermesc's own
// output drifts a few bytes across environments on identical input; the runtime still verifies
// the shipped hbc by its embedded SHA-256.
const generated = resolve(outDir, "kernel-entry.js");
const bytes0 = readFileSync(generated);
writeFileSync(tmpJs, bytes0);
console.log(
  `kernel-entry.js: ${bytes0.length} bytes, sha256 ${createHash("sha256").update(bytes0).digest("hex").slice(0, 16)}…`,
);

execFileSync(hermesc, ["-O", "-emit-async-break-check", "-emit-binary", "-out", tmpHbc, tmpJs], {
  stdio: ["ignore", "pipe", "inherit"],
});
const bytes = readFileSync(tmpHbc);
const sha256 = createHash("sha256").update(bytes).digest("hex");
rmSync(tmpJs);
rmSync(tmpHbc);

const body: string[] = [
  "// Generated by scripts/build-kernel.ts — do not edit.",
  "#pragma once",
  "",
  "#include <cstdint>",
  "#include <cstddef>",
  "",
  "namespace qntx {",
  "inline constexpr uint8_t KERNEL_BYTECODE[] = {",
];
for (let i = 0; i < bytes.length; i += 16) {
  const chunk = [...bytes.subarray(i, i + 16)]
    .map((b) => `0x${b.toString(16).padStart(2, "0")}`)
    .join(",");
  body.push(`  ${chunk}${i + 16 < bytes.length ? "," : ""}`);
}
body.push(
  "};",
  `inline constexpr size_t KERNEL_BYTECODE_SIZE = ${bytes.length};`,
  `inline constexpr char KERNEL_SHA256[] = "${sha256}";`,
  "}",
);
writeFileSync(resolve(outDir, "kernel.hpp"), `${body.join("\n")}\n`);
console.log(`kernel.hpp: ${bytes.length} bytes, sha256 ${sha256.slice(0, 16)}…`);
