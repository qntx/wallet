import { execFileSync } from "node:child_process";
/**
 * Build the kernel runtime payload: bundle `kernel/kernel-entry.ts` for the Hermes engine, compile
 * it to bytecode with the harness's hermesc (the same runtime the app ships), and emit
 * `cpp/generated/kernel.hpp` — the bytes plus their SHA-256, verified by `KernelHost::start`.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const harness = resolve(root, "apps/harness");
const entry = resolve(root, "packages/wallet-native/kernel/kernel-entry.ts");
const outDir = resolve(root, "packages/wallet-native/cpp/generated");
const tmp = resolve(outDir, ".kernel-entry.js");

const hermesc = (() => {
  const require = createRequire(resolve(harness, "package.json"));
  const pkg = require.resolve("hermes-compiler/package.json");
  const platformDir =
    process.platform === "darwin"
      ? "osx-bin"
      : process.platform === "linux"
        ? "linux64-bin"
        : "win64-bin";
  return resolve(
    dirname(pkg),
    "hermesc",
    platformDir,
    process.platform === "win32" ? "hermesc.exe" : "hermesc",
  );
})();

const run = (cmd: string[]): void => {
  execFileSync(cmd[0]!, cmd.slice(1), { stdio: ["ignore", "pipe", "inherit"] });
};

mkdirSync(outDir, { recursive: true });

// Bundle the entry for a bare Hermes runtime: CJS so hermesc accepts it, platform-neutral.
run(["bun", "build", entry, "--target", "bun", "--format", "cjs", "--outfile", tmp]);

const hbc = resolve(outDir, ".kernel.hbc");
run([hermesc, "-O", "-emit-async-break-check", "-emit-binary", "-out", hbc, tmp]);
const { readFileSync, rmSync } = await import("node:fs");
const bytes = readFileSync(hbc);
const sha256 = createHash("sha256").update(bytes).digest("hex");
rmSync(tmp);
rmSync(hbc);

const lines = bytes.length;
const body: string[] = [
  "// Generated by scripts/build-kernel.ts — do not edit.",
  "#pragma once",
  "",
  "#include <cstdint>",
  "#include <cstddef>",
  "",
  "namespace qntx {",
  `inline constexpr uint8_t KERNEL_BYTECODE[] = {`,
];
for (let i = 0; i < bytes.length; i += 16) {
  const chunk = [...bytes.subarray(i, i + 16)]
    .map((b) => `0x${b.toString(16).padStart(2, "0")}`)
    .join(",");
  body.push(`  ${chunk}${i + 16 < bytes.length ? "," : ""}`);
}
body.push(
  "};",
  `inline constexpr size_t KERNEL_BYTECODE_SIZE = ${lines};`,
  `inline constexpr char KERNEL_SHA256[] = "${sha256}";`,
  "}",
);
writeFileSync(resolve(outDir, "kernel.hpp"), `${body.join("\n")}\n`);
console.log(`kernel.hpp: ${bytes.length} bytes, sha256 ${sha256.slice(0, 16)}…`);
